                            <span>What is Fibropapillomatosis (FP)?</span>
                            <i class="fas fa-chevron-down"></i>
                        </button>
                        <div class="faq-answer">
                            <p>FP is a viral disease that causes tumor growth on sea turtles' soft tissues. Curaçao is one of four global hotspots for this disease. Approximately 80% of green turtles here carry the virus, though most remain healthy. Learn more on our <a href="fibropapillomatosis.php">FP information page</a>.</p>
