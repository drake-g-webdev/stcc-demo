                    <h2>Causes & Transmission</h2>
                    <p>Research suggests that FP is associated with a herpesvirus, specifically the Chelonid Herpesvirus 5 (ChHV5), also known as the sea turtle fibropapilloma-associated herpesvirus (STFV).</p>
                    <p>The mode of transmission is believed to occur through direct contact or exposure to the virus in contaminated water or infected turtles. Environmental factors, such as pollution and compromised immune systems, may also contribute to the development and spread of the disease.</p>
                    <p>One leading theory suggests that green turtles feeding on contaminated seagrass may have weakened immune systems, making them more susceptible to the virus.</p>
