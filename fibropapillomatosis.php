            <h2>The Situation in Curaçao</h2>
            <div class="fp-curacao-content">
                <p>FP has made its presence felt in sea turtle populations in Curaçao. The disease has been observed primarily in green turtles. In hawksbills and loggerhead turtles, FP doesn't occur often in the waters surrounding Curaçao. This may be due to the difference in food they forage on.</p>

                <p>The leading theory is that green turtles feed on seagrass that is contaminated, which weakens their immune system. <strong>On average, approximately 80% of the green turtle population in Curaçao is infected by FP, but with almost zero effects because of their overall good health condition.</strong> FP will cause severe illness and large tumors only in green turtles who are less healthy and whose immune response to the virus is insufficient.</p>

                <p>The prevalence of FP in Curaçao's sea turtles has raised concern among STCC and researchers visiting our island. Studies have shown that a significant proportion of green turtles in Curaçao's waters exhibit signs of the disease, with fibropapillomas affecting various parts of the soft tissues of their bodies, including the eyes, flippers, and reproductive organs.</p>

                <p>The exact reasons behind the high incidence of FP in Curaçao's sea turtles are still being investigated. Environmental factors such as pollution, habitat degradation, and compromised immune systems due to stressors like boat strikes or entanglement in fishing gear could potentially contribute to the development and spread of the disease.</p>
