                </div>
                <div class="impact-card">
                    <h3>Feeding & Breathing</h3>
                    <p>Tumors can obstruct the turtles' airways, making it difficult for them to breathe. Tumors around the mouth make eating difficult, leading to malnutrition.</p>
                </div>
                <div class="impact-card">
                    <h3>Organ Dysfunction</h3>
                    <p>Internal tumors may cause organ dysfunction or failure. In severe cases, FP can be fatal when vital organs are compromised.</p>
