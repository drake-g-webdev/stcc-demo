        <div class="container">
            <div class="section-header">
                <h2>Quick Image-Making Field Rules</h2>
                <p>The essential rules every STCC image maker must follow</p>
            </div>
            <div class="field-rules-grid">
                <div class="field-rule">
                    <i class="fas fa-camera-retro"></i>
                    <h3>No Posed Images With Turtles</h3>
                    <p>No "hero" shots. Documentary images of unfolding events only — never request someone to "hold that position and smile."</p>
                </div>
                <div class="field-rule">
                    <i class="fas fa-ban"></i>
                    <h3>No Selfies With Turtles</h3>
                    <p>Applies to all STCC members without exception.</p>
                </div>
                <div class="field-rule">
                    <i class="fas fa-bolt"></i>
                    <h3>No Flash</h3>
                    <p>Flash photography startles turtles, increases stress, and is illegal in some jurisdictions.</p>
                </div>
                <div class="field-rule">
                    <i class="fas fa-ruler-horizontal"></i>
                    <h3>Maintain A Safe Distance</h3>
                    <p>Use longer focal lengths to capture stress-free images. Protect both the turtle and yourself — turtles do bite.</p>
                </div>
                <div class="field-rule">
                    <i class="fas fa-user-shield"></i>
                    <h3>Don't Interfere With Work</h3>
                    <p>Document research or rescue efforts from a safe distance. Photograph the work; don't make the workers work around you.</p>
                </div>
                <div class="field-rule">
                    <i class="fas fa-hand-paper"></i>
                    <h3>Always Wear Gloves</h3>
                    <p>Disposable gloves are required when handling turtles or nests to prevent cross-contamination between sites.</p>
                </div>
                <div class="field-rule">
                    <i class="fas fa-fish"></i>
                    <h3>Never Bait, Feed, or Manipulate</h3>
                    <p>Wild turtles are not to be baited, fed, or manipulated for the sake of a better image.</p>
                </div>
                <div class="field-rule">
                    <i class="fas fa-question-circle"></i>
                    <h3>Ask When In Doubt</h3>
                    <p>Questionable images are reviewed by the Scientific Committee or Board before release. Ask for permission, not forgiveness.</p>
                </div>
            </div>
        </div>
    </section>

    <!-- Core Principles -->
    <section class="content-section">
        <div class="container">
            <div class="section-header">
                <h2>Core Principles</h2>
            </div>
            <div class="principles-list">
                <div class="principle-item">
                    <h3><i class="fas fa-heart"></i> Do No Harm</h3>
                    <p>This is the foundational guideline for STCC image makers. No photo or video will be made if its creation negatively impacts sea turtles or their environment. No added stress during research captures, no approaching wild turtles so closely that behavior is modified, never chase a turtle.</p>
                </div>
                <div class="principle-item">
                    <h3><i class="fas fa-balance-scale"></i> Follow The Law</h3>
                    <p>Sea turtles are all either threatened or endangered. STCC follows national and international law regarding sea turtle interactions, including image making during data collection and documentation.</p>
                </div>
                <div class="principle-item">
                    <h3><i class="fas fa-baby"></i> Never Portray Turtles As "Cute"</h3>
                    <p>Sea turtles are wild animals. They should never be cuddled, petted, hand fed, or treated as pets. Normalizing human-turtle interactions inadvertently recalibrates the public to expect or desire them.</p>
                </div>
                <div class="principle-item">
                    <h3><i class="fas fa-child"></i> Limited Child Imaging</h3>
                    <p>The STCC Board affirms that the faces of children will not be published on any STCC channels, even with parental permission. Minors age 15 and up may be photographed with proper consent.</p>
                </div>
                <div class="principle-item">
                    <h3><i class="fas fa-drone"></i> Strict Drone Policy</h3>
                    <p>Drones (UAVs) are prohibited during STCC events unless explicitly authorized in writing by the Scientific Committee and compliant with local aviation laws. Drones must never be flown within 100 meters of flamingos or near rescue helicopters.</p>
                </div>
                <div class="principle-item">
                    <h3><i class="fas fa-robot"></i> AI Disclosure Required</h3>
                    <p>AI-generated or significantly AI-altered images must be clearly labeled as such. Basic dust/spot removal tools are acceptable; any substantial AI modification is strictly prohibited without disclosure.</p>
                </div>
                <div class="principle-item">
                    <h3><i class="fas fa-eye"></i> Transparency & Honesty</h3>
                    <p>No overt misrepresentation. For example, we will not use images of Pacific Hawksbills when discussing local Curaçao Hawksbill turtles. Credibility takes years to earn and a moment to relinquish.</p>
                </div>
                <div class="principle-item">
                    <h3><i class="fas fa-copyright"></i> Copyright & Attribution</h3>
                    <p>Unless other arrangements are made, image makers retain copyright of their work. STCC always provides full photo credit. Watermarks are preserved in published images.</p>
                </div>
            </div>
        </div>
    </section>

